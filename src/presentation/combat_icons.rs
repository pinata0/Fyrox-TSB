#[derive(Default)]
struct Drawing(Vec<Primitive>);
impl Drawing {
    fn line(&mut self, a: (f32, f32), b: (f32, f32), thickness: f32) {
        self.0.push(Primitive::Line {
            begin: Vector2::new(a.0, a.1),
            end: Vector2::new(b.0, b.1),
            thickness,
        });
    }
    fn path(&mut self, points: &[(f32, f32)], thickness: f32) {
        for p in points.windows(2) {
            self.line(p[0], p[1], thickness);
        }
    }
    fn poly(&mut self, points: &[(f32, f32)]) {
        for i in 1..points.len() - 1 {
            self.0.push(Primitive::Triangle {
                points: [points[0], points[i], points[i + 1]].map(|(x, y)| Vector2::new(x, y)),
            });
        }
    }
    fn rect(&mut self, x: f32, y: f32, w: f32, h: f32) {
        self.poly(&[(x, y), (x + w, y), (x + w, y + h), (x, y + h)]);
    }
    fn circle(&mut self, x: f32, y: f32, r: f32, filled: bool) {
        self.0.push(if filled {
            Primitive::Circle {
                center: Vector2::new(x, y),
                radius: r,
                segments: 32,
            }
        } else {
            Primitive::WireCircle {
                center: Vector2::new(x, y),
                radius: r,
                thickness: 2.5,
                segments: 32,
            }
        });
    }
    fn star(&mut self, x: f32, y: f32, radius: f32) {
        let points: Vec<_> = (0..10)
            .map(|i| {
                let a = i as f32 * TAU / 10.0 - FRAC_PI_2;
                let r = if i % 2 == 0 { radius } else { radius * 0.44 };
                (x + a.cos() * r, y + a.sin() * r)
            })
            .collect();
        for i in 0..10 {
            self.poly(&[(x, y), points[i], points[(i + 1) % 10]]);
        }
    }
    fn shield(&mut self, x: f32, y: f32, w: f32, h: f32) {
        self.path(
            &[
                (x, y + 5.0),
                (x + w / 2.0, y),
                (x + w, y + 5.0),
                (x + w - 3.0, y + h * 0.65),
                (x + w / 2.0, y + h),
                (x + 3.0, y + h * 0.65),
                (x, y + 5.0),
            ],
            3.0,
        );
    }
    fn drop(&mut self, x: f32, y: f32, r: f32) {
        self.poly(&[(x, y - r * 1.8), (x + r * 0.9, y), (x - r * 0.9, y)]);
        self.circle(x, y, r, true);
    }
}

