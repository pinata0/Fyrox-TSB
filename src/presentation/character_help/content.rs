pub(super) fn race_guide(race: Race) -> (&'static str, &'static str, String) {
    match race {
        Race::Fairy | Race::Witch => (
            "서지", "SHIFT",
            format!("바라보는 방향으로 빠르게 질주합니다. 최대 {}회 충전되며 {}초마다 1회 회복합니다.\n{}", race_skill::SURGE_CHARGES, race_skill::SURGE_RECHARGE,
                if race == Race::Fairy { "요정 특성: 받는 치유량 +10%" } else { "마녀 특성: 일반 스킬 쿨타임 -5%" }),
        ),
        Race::Beast => ("도약", "SHIFT", format!("앞으로 크게 도약합니다. 지형을 넘거나 빠르게 접근할 때 사용하세요.\n재사용 대기시간 {}초", race_skill::LEAP_COOLDOWN)),
        Race::Spirit => ("잠복", "SHIFT", format!("최대 {}초간 땅속으로 숨습니다. 좌클릭을 {}초 누르면 올라옵니다. 종료 후 쿨타임 {}초.", race_skill::BURROW_DURATION, race_skill::EMERGE_HOLD, race_skill::BURROW_COOLDOWN)),
        Race::Ghost => ("벽 통과", "SHIFT", format!("{}초 동안 벽을 통과할 수 있습니다. 효과가 끝나기 전에 안전한 위치로 이동하세요.\n종료 후 재사용 대기시간 {}초", phase_skill::DURATION, phase_skill::COOLDOWN)),
        Race::Dragon => ("돌진", "SHIFT", format!("최대 {}초간 기본 이동속도의 {}배로 돌진하며 부딪힌 적에게 피해를 줍니다. 종료 후 쿨타임 {}초.\n용족 특성: 받는 밀쳐내기 -30%", race_skill::CHARGE_DURATION, race_skill::CHARGE_SPEED / movement::WALK_SPEED, race_skill::CHARGE_COOLDOWN)),
        Race::Elf => ("연결 포탈", "SHIFT + 클릭", format!("Shift + 좌클릭은 노랑, 우클릭은 파랑 포탈을 설치합니다. 각각 쿨타임 {}초. 통과 후 양쪽 포탈이 {}초간 닫혔다가 다시 열립니다.\n엘프 특성: 재장전 시간 -10%", portal::COOLDOWN, portal::REOPEN_DELAY)),
    }
}
